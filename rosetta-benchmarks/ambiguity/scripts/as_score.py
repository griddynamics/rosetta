#!/usr/bin/env python3
"""Ambiguity Score (AS) of the prompt versions (METRICS.md, section 1). Deterministic: no LLM.

  AS = 0.47 x coverage gap + 0.20 x vague density + 0.33 x contradiction load

- coverage gap: share of the checklist items the text leaves out, each counted by its weight
  (prompts/checklist.json; general items are not part of AS)
- vague density: number of phrases of prompts/vague-terms.txt in the text / 5, capped at 1 (a count, not
  divided by length: one vague point counts the same in a short and a long text; decision log #40)
- contradiction load: contradictions in the text / 2, capped at 1 (prompts: the planted ones)

The same functions score the agent's requirements (scripts/score_runs.py), so AS(prompt) and
AS(requirements) are computed the same way.

Usage (from the rosetta repo root):
  python3 rosetta-benchmarks/ambiguity/scripts/as_score.py --write

Standard library only. Same inputs give the same output.
"""
from __future__ import annotations

import argparse
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent  # rosetta-benchmarks/ambiguity
PROMPTS = ROOT / "prompts"
REPORTS = ROOT / "reports"
WEIGHTS = {"coverage_gap": 7 / 15, "vague_density": 3 / 15, "contradiction_load": 5 / 15}  # 0.47, 0.20, 0.33 (decision log #36)


def load_checklist(path: Path = PROMPTS / "checklist.json") -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def scored_items(checklist: dict) -> list[dict]:
    """The items that count for AS (not the general ones)."""
    return [i for i in checklist["items"] if not i.get("general")]


def load_terms(path: Path = PROMPTS / "vague-terms.txt") -> list[str]:
    terms = [ln.strip().lower() for ln in path.read_text(encoding="utf-8").splitlines()]
    terms = [t for t in terms if t and not t.startswith("#")]
    return sorted(set(terms), key=lambda t: (-len(t), t))  # longest first; ties in a fixed order


def vague_matches(text: str, terms: list[str]) -> list[str]:
    """Matches of the fixed term list, longest first; a matched span is not counted again."""
    low = text.lower()
    taken = [False] * len(low)
    found = []
    for term in terms:
        for m in re.finditer(r"(?<![\w])" + re.escape(term) + r"(?![\w])", low):
            if any(taken[m.start():m.end()]):
                continue
            for i in range(m.start(), m.end()):
                taken[i] = True
            found.append(term)
    return found


def word_count(text: str) -> int:
    return len(text.split())


def coverage_gap(stated: list[float], items: list[dict]) -> float:
    """stated[i] = 1 (stated), 0.5 (partly) or 0 (not stated) for scored item i."""
    total = sum(i["weight"] for i in items)
    return 1 - sum(i["weight"] * s for i, s in zip(items, stated)) / total


def vague_density(text: str, terms: list[str]) -> float:
    return min(1.0, len(vague_matches(text, terms)) / 5)


def contradiction_load(n: float) -> float:
    return min(1.0, n / 2)


def ambiguity(cov: float, vague: float, contra: float) -> float:
    return WEIGHTS["coverage_gap"] * cov + WEIGHTS["vague_density"] * vague + WEIGHTS["contradiction_load"] * contra


def prompt_scores(checklist: dict | None = None, terms: list[str] | None = None) -> list[dict]:
    checklist = checklist or load_checklist()
    terms = terms or load_terms()
    items = scored_items(checklist)
    rows = []
    for v in checklist["versions"]:
        text = (PROMPTS / f"{v}.txt").read_text(encoding="utf-8")
        stated = [1.0 if v in i["present_in"] else 0.0 for i in items]
        cov = coverage_gap(stated, items)
        vag = vague_density(text, terms)
        con = contradiction_load(sum(1 for c in checklist["contradictions"] if v in c["versions"]))
        rows.append({"version": v, "words": word_count(text), "vague_terms": "; ".join(vague_matches(text, terms)),
                     "coverage_gap": round(cov, 3), "vague_density": round(vag, 3), "contradiction_load": round(con, 3),
                     "as": round(ambiguity(cov, vag, con), 3)})
    return rows


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="write reports/as-scores.md and .csv")
    args = ap.parse_args()
    rows = prompt_scores()
    lines = ["# Ambiguity Score of the prompt versions (generated)", "",
             "Generated by `scripts/as_score.py`. Do not edit by hand. Formula: [METRICS.md](../METRICS.md), section 1.",
             "AS = 0.47 × coverage gap + 0.20 × vague density + 0.33 × contradiction load. No LLM.", "",
             "| Version | Words | Vague phrases found | Coverage gap | Vague density | Contradiction load | AS |",
             "| --- | ---: | --- | ---: | ---: | ---: | ---: |"]
    for r in rows:
        lines.append(f"| {r['version']} | {r['words']} | {r['vague_terms'] or '–'} | {r['coverage_gap']} | "
                     f"{r['vague_density']} | {r['contradiction_load']} | **{r['as']}** |")
    order = [r["as"] for r in rows]
    lines += ["", f"Rises strictly from v0 to v5: **{'yes' if all(a < b for a, b in zip(order, order[1:])) else 'no'}**."]
    text = "\n".join(lines) + "\n"
    print(text)
    if args.write:
        REPORTS.mkdir(exist_ok=True)
        (REPORTS / "as-scores.md").write_text(text, encoding="utf-8")
        with (REPORTS / "as-scores.csv").open("w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0]))
            w.writeheader()
            w.writerows(rows)


if __name__ == "__main__":
    main()
